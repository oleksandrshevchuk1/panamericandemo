const {readFileSync}=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const html=readFileSync('index.html','utf8');
const source=html.match(/<script id="domain">([\s\S]*?)<\/script>/)[1];
const context=vm.createContext({URL});vm.runInContext(source,context);
const {normalizePhone,calculateEstimate,validReference,routeProgress,reviewIndex,routeStage,routePathProgress}=context;
for(const raw of ['0975399248','380975399248','+380 (97) 539-92-48']) assert.equal(normalizePhone(raw),'+380975399248');
for(const raw of ['123','abc0975399248','+381975399248','']) assert.equal(normalizePhone(raw),null);
for(const raw of ['',0,-2,'NaN',Infinity,'1e309']) assert.throws(()=>calculateEstimate(raw,'standard'));
assert.throws(()=>calculateEstimate(5000,'unknown'));
const result=calculateEstimate(5000,'standard');
assert.equal(result.items.length,11);assert.equal(result.min,12700);assert.equal(result.max,16050);
assert.equal(result.items.reduce((s,i)=>s+i[1],0),result.min);
assert.equal(result.items.reduce((s,i)=>s+i[2],0),result.max);
assert.equal(validReference('https://example.com/lot/123'),true);
assert.equal(validReference('1HGCM82633A004352'),true);
assert.equal(validReference('javascript:alert(1)'),false);
assert.equal(validReference('INVALID'),false);
assert.equal(routeProgress(100,2200,900,false),0);
assert.equal(routeProgress(-650,2200,900,false),.5);
assert.equal(routeProgress(-2000,2200,900,false),1);
assert.equal(routeProgress(-100,2200,900,true),1);
assert.equal(routeProgress(0,500,900,false),0);
const suv=calculateEstimate(5000,'standard',{body:'suv'});
assert.ok(suv.min>result.min&&suv.max>result.max);
assert.throws(()=>calculateEstimate(5000,'standard',{year:1800}));
assert.equal(reviewIndex(-1,3),2);
assert.equal(reviewIndex(3,3),0);
assert.equal(reviewIndex(1,3),1);
assert.equal(routeStage(0),0);
assert.equal(routeStage(.2),1);
assert.equal(routeStage(.4),2);
assert.equal(routeStage(.55),3);
assert.equal(routeStage(.75),4);
assert.equal(routeStage(.95),5);
assert.equal(routeStage(1),5);
assert.equal(routePathProgress(0),0);assert.equal(routePathProgress(1),1);
let previousProgress=0;for(let i=0;i<=100;i++){const next=routePathProgress(i/100);assert.ok(next>=previousProgress&&next<=1);previousProgress=next;}
console.log('PASS: phone normalization, invalid estimates, full breakdown, reference validation');
