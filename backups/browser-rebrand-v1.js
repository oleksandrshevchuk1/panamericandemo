async (page) => {
  const assert=(condition,message)=>{if(!condition)throw new Error(message);};
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  page.on('console',msg=>{if(msg.type()==='error'&&msg.location().url.startsWith('http://127.0.0.1:4173'))errors.push(msg.text());});
  await page.goto('http://127.0.0.1:4173/');
  for(const [width,height] of [[1440,1000],[768,1024],[390,844],[360,740]]){
    await page.setViewportSize({width,height});
    await page.evaluate(()=>scrollTo({top:0,behavior:'instant'}));
    await page.waitForFunction(()=>document.fonts.status==='loaded');
    const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1);
    assert(!overflow,`Horizontal overflow at ${width}`);
    await page.screenshot({path:`checks/screenshots/panamerican-${width}.png`});
  }
  assert(await page.locator('.car').count()===11,'Missing cars');
  assert(await page.locator('.route-step').count()===8,'Missing route steps');
  assert(await page.locator('.video-card').count()===5,'Missing videos');
  await page.locator('.menu-toggle').click();
  assert(await page.locator('.menu-toggle').getAttribute('aria-expanded')==='true','Mobile menu failed');
  await page.locator('#navigation a[href="#calculator"]').click();
  assert(await page.locator('.menu-toggle').getAttribute('aria-expanded')==='false','Mobile menu not closed');
  await page.locator('#calculator-form button').click();
  await page.waitForFunction(()=>!document.querySelector('#calc-output').hidden);
  assert((await page.locator('#calc-total').innerText()).replace(/\D/g,'')==='12805','Wrong baseline estimate');
  await page.locator('#calc-consult').click();
  assert((await page.locator('#form-context').innerText()).includes('12'),'Estimate not transferred');
  await page.locator('#price').fill('6000');
  assert(await page.locator('#calc-output').isHidden(),'Stale estimate visible');
  assert(await page.locator('#form-context').isHidden(),'Stale transferred total visible');
  await page.locator('#price').fill('5000');
  await page.locator('#fuel').selectOption('elec');
  assert(await page.locator('#engine').isDisabled(),'EV engine must be disabled');
  await page.locator('#calculator-form button').click();
  assert((await page.locator('#calc-total').innerText()).replace(/\D/g,'')==='11108','Wrong EV estimate');
  await page.locator('#price').fill('1000');
  await page.locator('#calculator-form button').click();
  assert(await page.locator('#calc-warning').isVisible(),'Missing low-lot warning');
  await page.locator('#inquiry-name').fill('Тест');
  await page.locator('#inquiry-phone').fill('+380991234567');
  await page.locator('#inquiry-car').fill('Audi Q7');
  await page.locator('#inquiry-comment').fill('Перевірка локальної форми');
  await page.locator('#inquiry-form button[type="submit"]').click();
  assert(await page.locator('#form-message').isVisible(),'Inquiry not prepared');
  assert((await page.locator('#email-inquiry').getAttribute('href')).startsWith('mailto:pan.americanlviv@gmail.com?'),'Email target incorrect');
  await page.locator('.service-inquiry').first().click();
  assert(await page.locator('#form-message').isHidden(),'Prepared inquiry survives service change');
  await page.locator('#inquiry-name').fill('Інше ім’я');
  assert(await page.locator('#form-message').isHidden(),'Stale inquiry visible');
  await page.setViewportSize({width:1440,height:1000});
  await page.locator('#cars').evaluate(el=>scrollTo({top:el.offsetTop+600,behavior:'instant'}));
  await page.waitForFunction(()=>document.querySelector('.car.is-active')?.dataset.car!=='0');
  await page.evaluate(()=>Promise.all(document.getAnimations().map(a=>a.finished.catch(()=>{}))));
  await page.screenshot({path:'checks/screenshots/panamerican-gallery.png'});
  const galleryTop=await page.locator('.gallery-pin').evaluate(el=>el.getBoundingClientRect().top);
  assert(galleryTop>=85&&galleryTop<150,'Gallery must stay pinned below the header');
  const before=await page.locator('.car.is-active').getAttribute('data-car');
  await page.locator('#cars-next').click();
  await page.waitForFunction(previous=>document.querySelector('.car.is-active')?.dataset.car!==previous,before);
  await page.evaluate(()=>Promise.all(document.getAnimations().map(a=>a.finished.catch(()=>{}))));
  await page.locator('.car.is-active .car-details-button').click();
  assert(await page.locator('#car-dialog').isVisible(),'Vehicle details unavailable');
  assert((await page.locator('#car-dialog-condition').innerText()).includes('Пошкодження'),'Vehicle condition not disclosed');
  await page.keyboard.press('Escape');
  assert(await page.locator('#car-dialog').isHidden(),'Vehicle dialog does not close');
  await page.locator('#route').evaluate(el=>scrollTo({top:el.offsetTop+100,behavior:'instant'}));
  await page.waitForFunction(()=>document.querySelector('.route-step.active')?.dataset.step!=='0');
  await page.evaluate(()=>Promise.all(document.getAnimations().map(a=>a.finished.catch(()=>{}))));
  await page.screenshot({path:'checks/screenshots/panamerican-route-desktop.png'});
  const firstTransform=await page.locator('#route-traveler').getAttribute('transform');
  await page.evaluate(()=>scrollBy({top:300,behavior:'instant'}));
  await page.waitForFunction(previous=>document.querySelector('#route-traveler').getAttribute('transform')!==previous,firstTransform);
  await page.setViewportSize({width:390,height:844});
  await page.locator('#route').evaluate(el=>scrollTo({top:el.offsetTop+1100,behavior:'instant'}));
  await page.waitForFunction(()=>document.querySelector('#route').classList.contains('route-mobile-scene'));
  await page.screenshot({path:'checks/screenshots/panamerican-route-mobile.png'});
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.waitForFunction(()=>!document.querySelector('.gallery-shell').classList.contains('scroll-gallery'));
  assert(await page.locator('.car[aria-hidden="true"]').count()===0,'Reduced motion hides cars');
  await page.setViewportSize({width:1440,height:1000});
  await page.locator('#car-track').evaluate(el=>el.scrollTo({left:el.scrollWidth,behavior:'instant'}));
  await page.waitForFunction(()=>document.querySelector('#gallery-count').textContent==='11 / 11');
  assert(await page.locator('#cars-next').isDisabled(),'Last native gallery card is unreachable');
  await page.setViewportSize({width:390,height:844});
  await page.locator('#calculator').scrollIntoViewIfNeeded();
  await page.screenshot({path:'checks/screenshots/panamerican-calculator-mobile.png'});
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.reload();
  assert((await page.locator('#inquiry-name').inputValue())==='','Inquiry persisted after reload');
  assert(errors.length===0,'JavaScript errors: '+errors.join('; '));
  console.log('PASS: 4 viewport widths; menu; petrol + EV estimates; warnings; stale-total clearing; inquiry; scroll gallery; moving map; reduced motion; no persistence; no JS errors.');
}
